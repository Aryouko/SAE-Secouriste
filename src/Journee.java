package src;

public class Journee {
    private int jour;
    private int mois;
    private int annee;

    public getJour() {
        return this.jour;
    }

    public setJour(int jour) {
        this.jour = jour;
    }

    public getMois() {
        return this.mois;
    }

    public setMois(int mois) {
        this.mois = mois;
    }

    public getAnnee() {
        return this.annee;
    }

    public void setAnnee(int annee) {
        this.annee = annee;
    }
}
